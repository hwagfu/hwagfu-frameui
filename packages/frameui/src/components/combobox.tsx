/** Multi-select field: chosen values show as FrameON filter pills. */
function ComboboxChips({
  className,
  ...props
}: React.ComponentPropsWithRef<typeof ComboboxPrimitive.Chips> & ComboboxPrimitive.Chips.Props) {
  return (
    <ComboboxPrimitive.Chips
      data-slot="combobox-chips"
      className={cn(
        "flex min-h-[42px] flex-wrap items-center gap-1.5 rounded-md border border-input bg-field bg-clip-padding px-4 py-1.5 font-sans text-control text-foreground transition-[border-color,box-shadow] duration-150 focus-within:border-ring focus-within:shadow-focus focus-within:ring-1 focus-within:ring-ring has-aria-invalid:border-brand has-data-[slot=combobox-chip]:px-1.5",
        className
      )}
      {...props}
    />
  )
}

function ComboboxChip({
  className,
  children,
  showRemove = true,
  ...props
}: ComboboxPrimitive.Chip.Props & {
  showRemove?: boolean
}) {
  return (
    <ComboboxPrimitive.Chip
      data-slot="combobox-chip"
      className={cn(
        "flex h-7 w-fit items-center justify-center gap-1 rounded-full border border-brand bg-brand/12 px-2.5 font-sans text-caption font-medium whitespace-nowrap text-brand has-disabled:pointer-events-none has-disabled:cursor-not-allowed has-disabled:opacity-50 has-data-[slot=combobox-chip-remove]:pr-0.5 data-highlighted:bg-brand/25",
        className
      )}
      {...props}
    >
      {children}
      {showRemove && (
        <ComboboxPrimitive.ChipRemove
          render={<Button variant="ghost" size="icon-xs" />}
          className="size-6 text-brand/70 hover:text-brand"
          data-slot="combobox-chip-remove"
        >
          <XIcon className="pointer-events-none size-3" />
        </ComboboxPrimitive.ChipRemove>
      )}
    </ComboboxPrimitive.Chip>
  )
}

function ComboboxChipsInput({ className, ...props }: ComboboxPrimitive.Input.Props) {
  return (
    <ComboboxPrimitive.Input
      data-slot="combobox-chip-input"
      className={cn(
        "min-w-16 flex-1 border-0 bg-transparent font-sans text-control text-foreground outline-none placeholder:text-tertiary",
        className
      )}
      {...props}
    />
  )
}

/** Ref for the element the list should anchor to (e.g. `ComboboxChips`). */
function useComboboxAnchor() {
  return React.useRef<HTMLDivElement | null>(null)
}

